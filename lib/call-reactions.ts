export type CallReactionCustomId = (typeof CALL_REACTION_CUSTOM_IDS)[number]
export type CallReactionAssetId = (typeof CALL_REACTION_ASSET_IDS)[number]
export type CallReactionId = CallReactionCustomId | CallReactionAssetId

const CALL_REACTION_ID_SET = new Set<string>([
  ...CALL_REACTION_CUSTOM_IDS,
  ...CALL_REACTION_ASSET_IDS,
])

export function isCallReactionId(value: unknown): value is CallReactionId {
  return typeof value === 'string' && CALL_REACTION_ID_SET.has(value)
}

export function getCallReactionLabel(id: CallReactionAssetId): string {
  return id
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

export function getCallReactionAssetUrl(id: CallReactionAssetId): string {
  return `/animations/call-reactions/${id}.json`
}
